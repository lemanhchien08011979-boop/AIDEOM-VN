# CÂU 9.4.4 — Thêm ràng buộc: DisplacedJob[i] ≤ 5% × L[i] triệu
# L[i] tính bằng triệu người → đổi sang người: × 1.000.000
# c1 tính bằng việc/tỷ VND
# ═══════════════════════════════════════════════════════════════
print("=" * 65)
print("CÂU 9.4.4 — RÀNG BUỘC KHÔNG MẤT QUÁ 5% LAO ĐỘNG")
print("DisplacedJob[i] ≤ 0.05 × L[i] × 1.000.000")
print("=" * 65)

x_AI2 = cp.Variable(N, nonneg=True)
x_H2  = cp.Variable(N, nonneg=True)

NewJob2      = cp.multiply(a1, x_AI2)
UpgradeJob2  = cp.multiply(b1, x_H2)
DisplacedJob2 = cp.multiply(cp.multiply(c1, risk), x_AI2)
RetrainCap2  = cp.multiply(d1, x_H2)
NetJob2      = NewJob2 + UpgradeJob2 - DisplacedJob2

# Ràng buộc gốc
constraints2 = [
    cp.sum(x_AI2 + x_H2) <= 30000,
    NetJob2 >= 0,
    DisplacedJob2 <= RetrainCap2,
    x_AI2 >= 0,
    x_H2  >= 0,
]

# ★ Ràng buộc mới: DisplacedJob[i] ≤ 5% × L[i] × 1.000.000
# c1[i] × risk[i] × x_AI[i] ≤ 0.05 × L[i] × 1.000.000
L_nguoi = L * 1e6   # đổi triệu → người
for i_ng in range(N):
    constraints2.append(
        c1[i_ng] * risk[i_ng] * x_AI2[i_ng]
        <= 0.05 * L_nguoi[i_ng]
    )

prob2 = cp.Problem(cp.Maximize(cp.sum(NetJob2)), constraints2)
prob2.solve(solver=cp.HIGHS)

status2 = prob2.status
print(f"\nTrạng thái: {status2}")

if status2 in ['optimal', 'optimal_inaccurate']:
    x_AI2_val = x_AI2.value
    x_H2_val  = x_H2.value
    displaced2 = c1 * risk * x_AI2_val
    netjob2    = a1*x_AI2_val + b1*x_H2_val - displaced2

    print(f"\n✅ Bài toán VẪN KHẢ THI với ràng buộc 5%!")

    # So sánh với câu 9.4.1
    print("\n=== SO SÁNH: Không ràng buộc 5% vs Có ràng buộc 5% ===")
    print(f"  {'Ngành':22s} | {'NetJob gốc':>12} | "
          f"{'NetJob mới':>12} | {'Displaced gốc':>14} | "
          f"{'Displaced mới':>14} | {'5% L':>10}")
    print("  " + "─" * 90)
    for i in range(N):
        limit = 0.05 * L_nguoi[i]
        print(f"  {ten_viet[i]:22s} | "
              f"{NetJob_val[i]:>12.0f} | "
              f"{netjob2[i]:>12.0f} | "
              f"{DisplacedJob_val[i]:>14.0f} | "
              f"{displaced2[i]:>14.0f} | "
              f"{limit:>10.0f}")

    print(f"\n  Tổng NetJob gốc  = {NetJob_val.sum():>12,.0f}")
    print(f"  Tổng NetJob mới  = {netjob2.sum():>12,.0f}")
    delta = netjob2.sum() - NetJob_val.sum()
    print(f"  Thay đổi ΔNetJob = {delta:>12,.0f} "
          f"({'tăng ↑' if delta > 0 else 'giảm ↓'})")
    print(f"\n  📌 Chi phí của ràng buộc bảo vệ lao động:")
    print(f"     Giảm {abs(delta):,.0f} việc làm ròng "
          f"({abs(delta/NetJob_val.sum()*100):.1f}%)")
else:
    print(f"\n❌ Bài toán KHÔNG KHẢ THI với ràng buộc 5%!")
    print("  Kiểm tra ngành có L nhỏ + c1×risk cao:")
    for i in range(N):
        limit = 0.05 * L_nguoi[i]
        max_xAI = limit / (c1[i]*risk[i]) if c1[i]*risk[i] > 0 else np.inf
        print(f"  {ten_viet[i]:22s}: x_AI ≤ {max_xAI:,.0f} tỷ "
              f"(limit {limit:,.0f} việc)")

