# ═══════════════════════════════════════════════════════════════
# LỌC 8 NGÀNH (bỏ Khai khoáng id=4, Y tế id=10)
# ═══════════════════════════════════════════════════════════════
df = df_all[~df_all['sector_id'].isin([4, 10])].reset_index(drop=True)

ten_viet = [
    'Nông-Lâm-Thủy sản',
    'CN Chế biến-Chế tạo',
    'Xây dựng',
    'Bán buôn-Bán lẻ',
    'Tài chính-Ngân hàng',
    'Logistics-Vận tải',
    'CNTT-Truyền thông',
    'Giáo dục-Đào tạo',
]
df['sector_vi'] = ten_viet
N = len(df)   # = 8

print(f"Số ngành: {N}")
print(df[['sector_vi', 'labor_million', 'automation_risk_pct']].to_string(index=False))

# ═══════════════════════════════════════════════════════════════
# THAM SỐ 8 NGÀNH — Bảng 9.3 đề bài
# ═══════════════════════════════════════════════════════════════
# Lao động (triệu người)
L = df['labor_million'].values

# Rủi ro tự động hóa (%)
risk = df['automation_risk_pct'].values / 100.0  # đổi sang tỉ lệ

# Hệ số tạo việc làm mới từ AI (việc/tỷ VND)
a1 = np.array([8.5, 32.5, 12.8, 22.4, 45.8, 28.5, 62.5, 18.5])

# Hệ số tạo việc làm mới từ CĐS (việc/tỷ VND)
a2 = np.array([12.0, 18.5, 8.5, 15.2, 12.5, 16.8, 15.0, 22.0])

# Hệ số nâng cấp việc làm từ đào tạo (việc/tỷ VND)
b1 = np.array([45.0, 28.0, 35.0, 32.0, 22.0, 30.0, 20.0, 55.0])

# Hệ số dịch chuyển/thay thế từ AI (việc/tỷ VND)
c1 = np.array([5.2, 62.4, 18.5, 48.2, 72.5, 42.8, 32.5, 12.5])

# Hệ số năng lực đào tạo lại (việc/tỷ VND)
d1 = np.array([50.0, 32.0, 42.0, 38.0, 26.0, 36.0, 24.0, 62.0])

# In bảng tham số đầy đủ
print("\n=== BẢNG THAM SỐ 8 NGÀNH ===")
df_param = pd.DataFrame({
    'Ngành'      : ten_viet,
    'LĐ (tr)'    : L,
    'Risk (%)'   : (risk*100).astype(int),
    'a1'         : a1,
    'a2'         : a2,
    'b1'         : b1,
    'c1'         : c1,
    'd1'         : d1,
})
print(df_param.to_string(index=False))

# ═══════════════════════════════════════════════════════════════
# CÂU 9.4.1 — Tối đa hóa tổng NetJob
# Biến: x_AI[i], x_H[i] ≥ 0 (đầu tư AI và nhân lực mỗi ngành)
# Ràng buộc:
#   Σ(x_AI + x_H) ≤ 30.000 tỷ
#   NetJob[i] ≥ 0 ∀i
#   DisplacedJob[i] ≤ RetrainingCapacity[i] ∀i
# ═══════════════════════════════════════════════════════════════

x_AI = cp.Variable(N, nonneg=True, name='x_AI')
x_H  = cp.Variable(N, nonneg=True, name='x_H')

# Thành phần NetJob
NewJob      = cp.multiply(a1, x_AI)           # việc làm AI mới
UpgradeJob  = cp.multiply(b1, x_H)            # nâng cấp từ đào tạo
DisplacedJob = cp.multiply(cp.multiply(c1, risk), x_AI)  # bị thay thế
RetrainCap  = cp.multiply(d1, x_H)            # năng lực đào tạo lại

NetJob = NewJob + UpgradeJob - DisplacedJob

# Ràng buộc
constraints = [
    cp.sum(x_AI + x_H) <= 30000,   # ngân sách tổng
    NetJob >= 0,                    # không mất việc làm ròng
    DisplacedJob <= RetrainCap,     # đào tạo lại kịp thời
    x_AI >= 0,
    x_H  >= 0,
]

# Giải
prob = cp.Problem(cp.Maximize(cp.sum(NetJob)), constraints)
prob.solve(solver=cp.HIGHS)

status = prob.status
print("=" * 65)
print("CÂU 9.4.1 — KẾT QUẢ TỐI ƯU")
print(f"Trạng thái: {status}")
print("=" * 65)

if status in ['optimal', 'optimal_inaccurate']:
    x_AI_val = x_AI.value
    x_H_val  = x_H.value

    # Tính NetJob từng ngành
    NewJob_val      = a1 * x_AI_val
    UpgradeJob_val  = b1 * x_H_val
    DisplacedJob_val = c1 * risk * x_AI_val
    RetrainCap_val  = d1 * x_H_val
    NetJob_val      = NewJob_val + UpgradeJob_val - DisplacedJob_val

    # Bảng kết quả
    df_result = pd.DataFrame({
        'Ngành'         : ten_viet,
        'x_AI (tỷ)'     : x_AI_val.round(2),
        'x_H (tỷ)'      : x_H_val.round(2),
        'Tổng ĐT (tỷ)'  : (x_AI_val + x_H_val).round(2),
        'NewJob'         : NewJob_val.round(0).astype(int),
        'UpgradeJob'     : UpgradeJob_val.round(0).astype(int),
        'DisplacedJob'   : DisplacedJob_val.round(0).astype(int),
        'RetrainCap'     : RetrainCap_val.round(0).astype(int),
        'NetJob'         : NetJob_val.round(0).astype(int),
    })
    print(df_result.to_string(index=False))
    print(f"\n  Tổng đầu tư    : {(x_AI_val+x_H_val).sum():,.2f} tỷ VND")
    print(f"  Tổng NetJob    : {NetJob_val.sum():,.0f} việc làm")
    print(f"  Tỷ lệ AI/H     : {x_AI_val.sum():.0f} / {x_H_val.sum():.0f}")

    # Kiểm tra ràng buộc
    print("\n=== KIỂM TRA RÀNG BUỘC ===")
    all_ok = True
    for i, ten in enumerate(ten_viet):
        net_ok  = NetJob_val[i] >= -0.01
        retrain_ok = DisplacedJob_val[i] <= RetrainCap_val[i] + 0.01
        status_str = "✅" if (net_ok and retrain_ok) else "❌"
        if not (net_ok and retrain_ok):
            all_ok = False
        print(f"  {status_str} {ten:22s}: "
              f"NetJob={NetJob_val[i]:>8.0f} ≥ 0  |  "
              f"Displaced={DisplacedJob_val[i]:>6.0f} ≤ "
              f"Retrain={RetrainCap_val[i]:>6.0f}")
    print(f"\n  {'✅ Tất cả ràng buộc thỏa mãn!' if all_ok else '❌ Có ràng buộc vi phạm!'}")

    # Vẽ biểu đồ phân bổ và NetJob
    fig, axes = plt.subplots(1, 2, figsize=(14, 6))

    # Biểu đồ 1: Phân bổ x_AI và x_H
    ax1 = axes[0]
    x_pos = np.arange(N)
    w     = 0.35
    b1_bar = ax1.bar(x_pos - w/2, x_AI_val, w,
                     label='x_AI', color='#C44CE8',
                     edgecolor='white', linewidth=1.2)
    b2_bar = ax1.bar(x_pos + w/2, x_H_val,  w,
                     label='x_H',  color='#4C9BE8',
                     edgecolor='white', linewidth=1.2)
    ax1.set_xticks(x_pos)
    ax1.set_xticklabels(
        [t.replace('-', '\n') for t in ten_viet],
        fontsize=8)
    ax1.set_title('Phân bổ đầu tư tối ưu\nx_AI và x_H theo ngành',
                  fontsize=11, fontweight='bold')
    ax1.set_ylabel('Đầu tư (tỷ VND)')
    ax1.legend(); ax1.grid(axis='y', alpha=0.3)

    # Biểu đồ 2: NetJob breakdown
    ax2 = axes[1]
    ax2.bar(x_pos, NewJob_val + UpgradeJob_val,
            label='Tạo việc mới + Nâng cấp',
            color='#4CE882', edgecolor='white', linewidth=1.2)
    ax2.bar(x_pos, -DisplacedJob_val,
            label='Mất việc (Displaced)',
            color='#E84C4C', edgecolor='white', linewidth=1.2)
    ax2.plot(x_pos, NetJob_val, 'ko--',
             linewidth=2, markersize=8, label='NetJob ròng',
             zorder=5)
    ax2.axhline(y=0, color='gray', linewidth=1.5)
    for i, v in enumerate(NetJob_val):
        ax2.annotate(f'{v:,.0f}',
                     xy=(i, v + 50),
                     ha='center', fontsize=8,
                     fontweight='bold', color='navy')
    ax2.set_xticks(x_pos)
    ax2.set_xticklabels(
        [t.replace('-', '\n') for t in ten_viet],
        fontsize=8)
    ax2.set_title('Phân rã NetJob từng ngành\n'
                  'Tạo mới vs Mất việc vs Ròng',
                  fontsize=11, fontweight='bold')
    ax2.set_ylabel('Số việc làm')
    ax2.legend(fontsize=9); ax2.grid(axis='y', alpha=0.3)

    plt.suptitle('Bài 9 — Tác động AI tới Thị trường Lao động Việt Nam',
                 fontsize=13, fontweight='bold')
    plt.tight_layout()
    plt.savefig('bai9_cau1_optimal.png', dpi=150, bbox_inches='tight')
    plt.show()

