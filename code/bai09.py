# CÂU 9.4.2 — Ngưỡng x_H tối thiểu cho ngành 2 (CN chế biến)
# để NetJob₂ ≥ 0 khi x_AI₂ tối đa
# ═══════════════════════════════════════════════════════════════
print("=" * 65)
print("CÂU 9.4.2 — NGƯỠNG ĐÀO TẠO TỐI THIỂU NGÀNH 2")
print("(CN Chế biến-Chế tạo — Rủi ro TĐH cao nhất: 42%)")
print("=" * 65)

i = 1   # index ngành 2 (0-based)

# Giải tích: NetJob₂ ≥ 0
# a1[i]·x_AI + b1[i]·x_H - c1[i]·risk[i]·x_AI ≥ 0
# (a1[i] - c1[i]·risk[i])·x_AI + b1[i]·x_H ≥ 0
net_coeff_AI = a1[i] - c1[i]*risk[i]
print(f"\n  Hệ số ròng của x_AI trong NetJob₂:")
print(f"  a1={a1[i]} - c1={c1[i]} × risk={risk[i]:.2f} "
      f"= {net_coeff_AI:.3f}")

if net_coeff_AI >= 0:
    print(f"  → x_AI tự tạo ra NetJob dương → "
          f"x_H tối thiểu = 0")
else:
    print(f"  → x_AI gây mất việc ròng "
          f"→ cần x_H bù đắp")

# Quét x_AI_2 từ 0 → 5000 tỷ
x_AI2_range = np.linspace(0, 5000, 200)
xH_min_list = []

for x_ai2 in x_AI2_range:
    # NetJob₂ ≥ 0:
    # a1·x_ai + b1·x_h - c1·risk·x_ai ≥ 0
    # x_h ≥ (c1·risk - a1)·x_ai / b1
    xH_min = max(0, (c1[i]*risk[i] - a1[i]) * x_ai2 / b1[i])
    xH_min_list.append(xH_min)

# Thêm ràng buộc Displaced ≤ RetrainCap
# c1·risk·x_ai ≤ d1·x_h → x_h ≥ c1·risk·x_ai / d1
xH_retrain_list = [
    c1[i]*risk[i]*x_ai2 / d1[i]
    for x_ai2 in x_AI2_range
]
xH_binding = [max(a, b) for a, b in
              zip(xH_min_list, xH_retrain_list)]

# Điểm khi x_AI₂ = tối đa trong kịch bản cơ sở
x_AI2_opt = x_AI_val[i]
xH2_min   = max(
    (c1[i]*risk[i] - a1[i]) * x_AI2_opt / b1[i],
    c1[i]*risk[i]*x_AI2_opt / d1[i],
    0
)
print(f"\n  Khi x_AI₂ = {x_AI2_opt:.2f} tỷ (từ câu 9.4.1):")
print(f"  x_H₂ tối thiểu (NetJob≥0)      = {(c1[i]*risk[i]-a1[i])*x_AI2_opt/b1[i]:.2f} tỷ")
print(f"  x_H₂ tối thiểu (Retrain đủ)    = {c1[i]*risk[i]*x_AI2_opt/d1[i]:.2f} tỷ")
print(f"  ⟹ x_H₂ ràng buộc chặt nhất    = {xH2_min:.2f} tỷ")
print(f"  x_H₂ trong nghiệm tối ưu       = {x_H_val[i]:.2f} tỷ "
      f"{'✅' if x_H_val[i] >= xH2_min-0.01 else '❌'}")

# Vẽ đồ thị
fig, ax = plt.subplots(figsize=(10, 5))
ax.plot(x_AI2_range, xH_min_list,
        color='#4C9BE8', linewidth=2.5,
        label='x_H₂ min (NetJob ≥ 0)')
ax.plot(x_AI2_range, xH_retrain_list,
        color='#E87A4C', linewidth=2.5, linestyle='--',
        label='x_H₂ min (Retrain đủ)')
ax.plot(x_AI2_range, xH_binding,
        color='#E84C4C', linewidth=2.5, linestyle='-.',
        label='x_H₂ ràng buộc chặt nhất')

ax.axvline(x=x_AI2_opt, color='purple',
           linewidth=2, linestyle=':',
           label=f'x_AI₂ tối ưu = {x_AI2_opt:.0f} tỷ')
ax.scatter([x_AI2_opt], [xH2_min],
           color='red', s=150, zorder=5,
           label=f'Ngưỡng x_H₂ = {xH2_min:.1f} tỷ')

ax.set_title('Ngưỡng đầu tư đào tạo tối thiểu — Ngành CN Chế biến\n'
             'để NetJob₂ ≥ 0 theo mức đầu tư AI',
             fontsize=12, fontweight='bold')
ax.set_xlabel('x_AI₂ (tỷ VND)')
ax.set_ylabel('x_H₂ tối thiểu (tỷ VND)')
ax.legend(fontsize=9); ax.grid(alpha=0.3)
plt.tight_layout()
plt.savefig('bai9_cau2_threshold.png', dpi=150, bbox_inches='tight')
plt.show()

