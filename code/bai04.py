print("=" * 65)
print("CÂU 4.4.4 — CHI PHÍ KINH TẾ CỦA CÔNG BẰNG VÙNG MIỀN")
print("=" * 65)

# ── Mô hình KHÔNG có C5 (bỏ ràng buộc công bằng) ──────────
mdl2 = pulp.LpProblem("VN_Budget_NoC5", pulp.LpMaximize)
x2   = pulp.LpVariable.dicts('x2', (REGIONS, ITEMS), lowBound=0)

mdl2 += pulp.lpSum(BETA[(r,j)] * x2[r][j]
                   for r in REGIONS for j in ITEMS)

# C1, C2, C3, C4 giữ nguyên — BỎ C5
mdl2 += pulp.lpSum(x2[r][j] for r in REGIONS for j in ITEMS) <= 50000

for r in REGIONS:
    mdl2 += pulp.lpSum(x2[r][j] for j in ITEMS) >= 5000
    mdl2 += pulp.lpSum(x2[r][j] for j in ITEMS) <= 12000

mdl2 += pulp.lpSum(x2[r]['H'] for r in REGIONS) >= 12000

mdl2.solve(pulp.PULP_CBC_CMD(msg=False))

Z_no_c5    = pulp.value(mdl2.objective)
alloc_no_c5 = np.array([
    [pulp.value(x2[r][j]) for j in ITEMS]
    for r in REGIONS
])

# ── Tính chi phí kinh tế ───────────────────────────────────
equity_cost   = Z_no_c5 - Z_pulp
equity_pct    = equity_cost / Z_no_c5 * 100

print(f"\n  Z* CÓ C5  (có công bằng)  = {Z_pulp:>12,.2f}  tỷ VND")
print(f"  Z* BỎ C5  (không C5)      = {Z_no_c5:>12,.2f}  tỷ VND")
print(f"\n  💸 Chi phí kinh tế công bằng = {equity_cost:>10,.2f}  tỷ VND GDP gain")
print(f"     Tương đương {equity_pct:.2f}% tổng GDP gain bị hi sinh")
print(f"     để đảm bảo mọi vùng đạt ≥ {LAMBDA*100:.0f}% mức số hóa cao nhất")

# ── Bảng so sánh hai phương án ─────────────────────────────
df_c5    = pd.DataFrame(alloc_pulp,  index=REGION_NAMES_VI, columns=ITEM_NAMES)
df_no_c5 = pd.DataFrame(alloc_no_c5, index=REGION_NAMES_VI, columns=ITEM_NAMES)
df_c5["TỔNG"]    = df_c5.sum(axis=1)
df_no_c5["TỔNG"] = df_no_c5.sum(axis=1)

print(f"\n─── Phân bổ CÓ C5 (Z* = {Z_pulp:,.0f} tỷ) ─────────────────")
print(df_c5.round(0).to_string())

print(f"\n─── Phân bổ BỎ C5 (Z* = {Z_no_c5:,.0f} tỷ) ─────────────────")
print(df_no_c5.round(0).to_string())

# ── Vẽ biểu đồ 3 panel ────────────────────────────────────
fig, axes = plt.subplots(1, 3, figsize=(18, 5), facecolor="#F4F6F9")

