axes[1].set_title("Cơ cấu hạng mục trong từng vùng (%)",
                  fontsize=12, fontweight="bold", color="#1B4F72")
axes[1].tick_params(axis="x", rotation=20, labelsize=9)
axes[1].tick_params(axis="y", rotation=0, labelsize=9)

plt.suptitle("CÂU 4.4.3 — Heatmap phân bổ ngân sách số tối ưu theo vùng-hạng mục",
             fontsize=13, fontweight="bold", color="#1B4F72", y=1.02)
plt.tight_layout()
plt.show()

# ── Nhận xét tóm tắt ───────────────────────────────────────
tong_vung     = df_heat.sum(axis=1).sort_values(ascending=False)
uu_tien_vung  = df_heat.idxmax(axis=1)

print("\n📊 Tổng ngân sách mỗi vùng & hạng mục ưu tiên:")
print(f"{'Vùng':<28} {'Tổng (tỷ)':>10}   Ưu tiên")
print("─" * 58)
for vung in tong_vung.index:
    print(f"  {vung:<26} {tong_vung[vung]:>10,.0f}   {uu_tien_vung[vung]}")

print(f"\n► Vùng nhận nhiều nhất : {tong_vung.index[0]}  ({tong_vung.iloc[0]:,.0f} tỷ)")
print(f"► Vùng nhận ít nhất    : {tong_vung.index[-1]}  ({tong_vung.iloc[-1]:,.0f} tỷ)")

# ============================================================
# CELL 6 — CÂU 4.4.4: So sánh có/không có ràng buộc C5
# Tính chi phí kinh tế của công bằng vùng miền
