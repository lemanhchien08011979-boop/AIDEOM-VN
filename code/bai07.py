class VietnamDigitalProblem(ElementwiseProblem):
    def __init__(self):
        super().__init__(
            n_var=24,
            n_obj=4,
            n_ieq_constr=14,
            xl=np.zeros(24),
            xu=np.ones(24) * 12000,
        )
        self.beta = BETA_MAT
        self.e    = E
        self.rho  = RHO
        self.sig  = SIG

    def _evaluate(self, x, out, *args, **kwargs):
        X = x.reshape(NR, NJ)

        f1 = -(self.beta * X).sum()
        sums = X.sum(axis=1)
        f2 = np.abs(sums - sums.mean()).mean()
        f3 = (self.e * (X[:,0] + X[:,2])).sum()
        f4 = (self.rho * X[:,2]).sum() - (self.sig * X[:,3]).sum()

        out['F'] = [f1, f2, f3, f4]

        g = []
        g.append(X.sum() - BUDGET_TOTAL)
        for r in range(NR):
            g.append(FLOOR_REGION - X[r,:].sum())
        for r in range(NR):
            g.append(X[r,:].sum() - CEIL_REGION)
        g.append(FLOOR_H - X[:,3].sum())
        out['G'] = g

