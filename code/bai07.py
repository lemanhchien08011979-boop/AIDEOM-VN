def topsis(F_matrix, weights, is_benefit):
    """
    TOPSIS chuẩn cho tập nghiệm Pareto.
    F_matrix: (n_solutions, n_objectives)
    Trả về: mảng C* và index nghiệm tốt nhất
    """
    n = F_matrix.shape[0]
    # Chuẩn hóa vector
    norms = np.sqrt((F_matrix**2).sum(axis=0))
    norms[norms == 0] = 1e-12
    R = F_matrix / norms
    V = R * weights  # nhân trọng số

    # Lý tưởng dương & âm
    A_star = np.array([
        V[:, j].max() if is_benefit[j] else V[:, j].min()
        for j in range(len(weights))
    ])
    A_neg = np.array([
        V[:, j].min() if is_benefit[j] else V[:, j].max()
        for j in range(len(weights))
    ])

    # Khoảng cách Euclide
    S_star = np.sqrt(((V - A_star)**2).sum(axis=1))
    S_neg  = np.sqrt(((V - A_neg )**2).sum(axis=1))

    # Hệ số gần gũi
    C_star = S_neg / (S_star + S_neg + 1e-12)
    best   = np.argmax(C_star)
    return C_star, best

