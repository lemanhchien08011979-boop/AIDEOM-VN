# Tham số Q-learning
LR      = 0.1    # learning rate α
GAMMA   = 0.95   # discount factor
EPS_START = 1.0
EPS_END   = 0.05
N_EPISODES = 10000

# Bảng Q: shape (3,3,3,3,5) = 81 trạng thái × 5 hành động
Q = np.zeros((3, 3, 3, 3, 5))

# Lưu reward mỗi episode để vẽ learning curve
episode_rewards = []

print(f"\n⏳ Đang huấn luyện {N_EPISODES} episodes...\n")

for ep in range(N_EPISODES):
    # Epsilon giảm tuyến tính từ EPS_START → EPS_END
    eps = max(EPS_END, EPS_START - ep / 5000)

    s, _ = env.reset()
    total_r = 0.0

    while True:
        # Epsilon-greedy
        if np.random.rand() < eps:
            a = env.action_space.sample()
        else:
            a = int(np.argmax(Q[tuple(s)]))

        s2, r, done, _, _ = env.step(a)

        # Cập nhật Q-table
        Q[tuple(s) + (a,)] += LR * (
            r + GAMMA * Q[tuple(s2)].max() - Q[tuple(s) + (a,)]
        )

        total_r += r
        s = s2
        if done:
            break

    episode_rewards.append(total_r)

    # In tiến độ mỗi 2000 episodes
    if (ep + 1) % 2000 == 0:
        avg = np.mean(episode_rewards[-200:])
        print(f"  Episode {ep+1:>6} | ε={eps:.3f} | avg reward (200 eps) = {avg:.4f}")

