class VietnamEconomyEnv(gym.Env):
    """
    Môi trường MDP mô phỏng kinh tế Việt Nam 2026-2035.

    Trạng thái: [gdp_growth, digital, ai_capacity, unemp_risk]
                mỗi chiều: 0=low, 1=medium, 2=high
    Hành động : 0-4 (5 chiến lược phân bổ ngân sách)
    Reward    : R = w1*ΔGDP - w2*Δunemp - w3*CyberRisk - w4*Emission
    Episode   : T=10 bước (2026-2035)
    """

    metadata = {"render_modes": []}

    def __init__(self):
        super().__init__()
        self.action_space      = spaces.Discrete(5)
        self.observation_space = spaces.MultiDiscrete([3, 3, 3, 3])
        self.T = 10

    def _digitize_state(self, K, D, AI, H, gdp_growth):
        """Chuyển giá trị liên tục → trạng thái rời rạc."""
        g  = 0 if gdp_growth < 5 else (1 if gdp_growth < 8 else 2)
        d  = 0 if D < 15        else (1 if D < 25        else 2)
        ai = 0 if AI < 80       else (1 if AI < 120      else 2)
        # Unemployment risk: proxy ngược H
        # H<25% → rủi ro cao (2), 25-35% → trung bình (1), >35% → thấp (0)
        u  = 2 if H < 25        else (1 if H < 35        else 0)
        return np.array([g, d, ai, u], dtype=np.int64)

    def reset(self, seed=None, options=None):
        super().reset(seed=seed)
        # Điều kiện ban đầu VN 2026 (từ đề bài)
        self.K    = 27500.0
        self.D    = 20.3
        self.AI   = 86.0
        self.H    = 30.0
        self.A    = A0
        self.t    = 0
        # Trạng thái VN 2026: GDP=medium(7%), D=medium(20%), AI=medium(86k), U=medium
        self.state = self._digitize_state(self.K, self.D, self.AI, self.H, 7.0)
        return self.state.copy(), {}

    def step(self, action):
        a    = ALLOCATION[action]

        # ── Cập nhật trạng thái ────────────────────────────
        I_K  = a[0] * BUDGET
        I_D  = a[1] * BUDGET / 100     # → đơn vị % GDP
        I_AI = a[2] * BUDGET / 20      # → nghìn DN số
        I_H  = a[3] * BUDGET / 200     # → % lao động

        Y_old = (self.A * self.K**ALPHA * L_FIXED**BETA_L *
                 self.D**GAMMA_D * self.AI**DELTA_AI * self.H**THETA_H)

        self.K  = (1 - 0.05)  * self.K  + I_K
        self.D  = (1 - 0.12)  * self.D  + I_D
        self.AI = (1 - 0.15)  * self.AI + I_AI
        self.H  = self.H + 0.8 * I_H - 0.02 * self.H
        self.A  = self.A * (1 + TFP_RATE)

        Y_new = (self.A * self.K**ALPHA * L_FIXED**BETA_L *
                 self.D**GAMMA_D * self.AI**DELTA_AI * self.H**THETA_H)

        gdp_growth = (Y_new - Y_old) / Y_old * 100

        # ── Tính reward ────────────────────────────────────
        delta_gdp   = gdp_growth
        delta_unemp = max(0.0, 25.0 - self.H) * 0.1
        cyber_risk  = a[2] * 0.5
        emission    = (a[0] + a[2]) * 0.3

        reward = (W[0] * delta_gdp
                  - W[1] * delta_unemp
                  - W[2] * cyber_risk
                  - W[3] * emission)

        # ── Chuyển trạng thái ─────────────────────────────
        self.state = self._digitize_state(
            self.K, self.D, self.AI, self.H, gdp_growth
        )

        self.t += 1
        terminated = self.t >= self.T
        return self.state.copy(), reward, terminated, False, {
            'Y': Y_new, 'gdp_growth': gdp_growth,
            'K': self.K, 'D': self.D, 'AI': self.AI, 'H': self.H
        }

