# ═══════════════════════════════════════════════════════════════
# CÂU 10.5.1 — Pyomo với Set, Param, Var rõ ràng
# Mô hình hóa first-stage VÀ second-stage tường minh
# ═══════════════════════════════════════════════════════════════

m = pyo.ConcreteModel(name="Stochastic_SP_Bai10")

# ── SETS ─────────────────────────────────────────────────────
m.J = pyo.Set(initialize=J,
              doc="Tập hạng mục đầu tư: I, D, AI, H")
m.S = pyo.Set(initialize=S,
              doc="Tập kịch bản: s1, s2, s3, s4")

# ── PARAMS ───────────────────────────────────────────────────
m.p = pyo.Param(
    m.S, initialize=p,
    doc="Xác suất từng kịch bản")

m.beta = pyo.Param(
    m.J, initialize=beta,
    doc="Hệ số GDP giai đoạn 1 (first-stage)")

m.beta_s = pyo.Param(
    m.S, m.J, initialize=beta_s,
    doc="Hệ số GDP giai đoạn 2 theo kịch bản")

m.NS1 = pyo.Param(
    initialize=NS_1,
    doc="Ngân sách giai đoạn 1 = 65.000 tỷ")

m.NS2 = pyo.Param(
    initialize=NS_2,
    doc="Ngân sách giai đoạn 2 = 15.000 tỷ")

# ── VARIABLES ────────────────────────────────────────────────
m.x = pyo.Var(
    m.J,
    within=pyo.NonNegativeReals,
    doc="FIRST-STAGE: x[j] = đầu tư hạng mục j giai đoạn 1")

m.y = pyo.Var(
    m.S, m.J,
    within=pyo.NonNegativeReals,
    doc="SECOND-STAGE: y[s,j] = đầu tư bổ sung kịch bản s")

# ── HÀM MỤC TIÊU ─────────────────────────────────────────────
# max Σβⱼ·xⱼ + Σₛ pₛ·Σⱼ βⱼˢ·yⱼˢ
def obj_rule(m):
    first_stage = sum(m.beta[j] * m.x[j] for j in m.J)
    second_stage = sum(
        m.p[s] * sum(m.beta_s[s,j] * m.y[s,j] for j in m.J)
        for s in m.S
    )
    return first_stage + second_stage

m.obj = pyo.Objective(
    rule=obj_rule,
    sense=pyo.maximize,
    doc="Tối đa hóa GDP kỳ vọng 2 giai đoạn")

# ── RÀNG BUỘC ────────────────────────────────────────────────
# R1: Ngân sách giai đoạn 1
m.R1_budget1 = pyo.Constraint(
    expr=sum(m.x[j] for j in m.J) <= m.NS1,
    doc="NS giai đoạn 1 ≤ 65.000 tỷ")

# R2: Ngân sách giai đoạn 2 mỗi kịch bản
def R2_budget2(m, s):
    return sum(m.y[s,j] for j in m.J) <= m.NS2
m.R2_budget2 = pyo.Constraint(
    m.S, rule=R2_budget2,
    doc="NS giai đoạn 2 ≤ 15.000 tỷ mỗi kịch bản")

# R3: AI cần nhân lực — yᴬᴵˢ ≤ 0.5·x_H
def R3_ai_labor(m, s):
    return m.y[s,'AI'] <= 0.5 * m.x['H']
m.R3_ai_labor = pyo.Constraint(
    m.S, rule=R3_ai_labor,
    doc="Đầu tư AI stage 2 ≤ 50% nhân lực stage 1")

# ── GIẢI ─────────────────────────────────────────────────────
solver = pyo.SolverFactory('glpk')
result = solver.solve(m, tee=False)
status = str(result.solver.termination_condition)

print("=" * 60)
print("CÂU 10.5.1 — KẾT QUẢ STOCHASTIC PROGRAMMING")
print("=" * 60)
print(f"\n  Solver : GLPK")
print(f"  Trạng thái: {status}")
print(f"  Z* (SP) = {pyo.value(m.obj):,.4f}")

# Lưu kết quả SP
x_SP  = {j: pyo.value(m.x[j]) for j in J}
y_SP  = {(s,j): pyo.value(m.y[s,j]) for s in S for j in J}
Z_SP  = pyo.value(m.obj)

# Báo cáo FIRST-STAGE
print("\n=== QUYẾT ĐỊNH FIRST-STAGE TỐI ƯU ===")
print(f"  {'Hạng mục':20s} | {'x* (tỷ VND)':>12} | {'Tỷ trọng':>10}")
