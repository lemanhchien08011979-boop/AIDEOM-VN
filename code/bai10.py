# ═══════════════════════════════════════════════════════════════

# Hạng mục đầu tư
J = ['I', 'D', 'AI', 'H']
ten_hang_muc = {
    'I' : 'Hạ tầng số',
    'D' : 'Chuyển đổi số',
    'AI': 'Trí tuệ nhân tạo',
    'H' : 'Nhân lực số'
}

# Kịch bản bất định
S = ['s1', 's2', 's3', 's4']
ten_kich_ban = {
    's1': 'Lạc quan',
    's2': 'Cơ sở',
    's3': 'Bi quan',
    's4': 'Khủng hoảng'
}

# Xác suất từng kịch bản — Bảng 10.2
p = {'s1': 0.30, 's2': 0.45, 's3': 0.20, 's4': 0.05}

# Hệ số β cơ bản giai đoạn 1
beta = {'I': 1.00, 'D': 1.10, 'AI': 1.25, 'H': 0.95}

# Hệ số β theo kịch bản giai đoạn 2 — Bảng 10.4
beta_s = {
    ('s1','I'): 1.25, ('s1','D'): 1.35, ('s1','AI'): 1.55, ('s1','H'): 1.05,
    ('s2','I'): 1.00, ('s2','D'): 1.10, ('s2','AI'): 1.25, ('s2','H'): 0.95,
    ('s3','I'): 0.75, ('s3','D'): 0.85, ('s3','AI'): 0.90, ('s3','H'): 1.00,
    ('s4','I'): 0.40, ('s4','D'): 0.50, ('s4','AI'): 0.55, ('s4','H'): 1.10,
}

# Ngân sách
NS_1   = 65000   # giai đoạn 1
NS_2   = 15000   # giai đoạn 2
NS_TOT = 80000   # tổng

# ── In kiểm tra ──────────────────────────────────────────────
print("=" * 55)
print("DỮ LIỆU BÀI 10 — Quy hoạch ngẫu nhiên 2 giai đoạn")
print("=" * 55)

