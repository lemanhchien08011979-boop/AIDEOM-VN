def entropy_weights(X):
    """
    Tính trọng số khách quan bằng phương pháp Entropy
    Bước 1: Chuẩn hóa P_ij = x_ij / Σx_ij
    Bước 2: Tính entropy E_j = -k × Σ P_ij × ln(P_ij)
    Bước 3: Độ phân kỳ d_j = 1 - E_j
    Bước 4: Trọng số w_j = d_j / Σd_j
    """
    # Bước 1: Chuẩn hóa theo cột
    P = X / X.sum(axis=0)

    # Bước 2: Entropy (thêm 1e-12 để tránh log(0))
    k = 1.0 / np.log(len(X))
    E = -k * np.nansum(P * np.log(P + 1e-12), axis=0)

    # Bước 3: Độ phân kỳ
    d = 1 - E

    # Bước 4: Trọng số
    w = d / d.sum()
    return w, E, d


