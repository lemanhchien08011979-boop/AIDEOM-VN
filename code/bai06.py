# CÂU 6.4.4 — AHP đơn giản (so sánh cặp)
# ═══════════════════════════════════════════════════════════════
def ahp_weights(pairwise_matrix):
    """
    Tính trọng số AHP từ ma trận so sánh cặp
    Bước 1: Chuẩn hóa cột
    Bước 2: Tính trung bình hàng = trọng số ưu tiên
    Bước 3: Kiểm tra CR (Consistency Ratio)
    """
    A = np.array(pairwise_matrix, dtype=float)
    n = A.shape[0]

    # Bước 1: Chuẩn hóa
    col_sum = A.sum(axis=0)
    A_norm  = A / col_sum

    # Bước 2: Trọng số = trung bình hàng
    w = A_norm.mean(axis=1)

    # Bước 3: CR
    Aw     = A @ w
    lambda_max = (Aw / w).mean()
    CI     = (lambda_max - n) / (n - 1)
    # RI bảng Saaty
    RI_table = {1:0, 2:0, 3:0.58, 4:0.90, 5:1.12,
                6:1.24, 7:1.32, 8:1.41}
    RI = RI_table.get(n, 1.45)
    CR = CI / RI if RI > 0 else 0

    return w, lambda_max, CI, CR


