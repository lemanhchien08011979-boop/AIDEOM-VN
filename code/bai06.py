# HÀM TOPSIS — cài đặt từ đầu bằng numpy
# ═══════════════════════════════════════════════════════════════
def topsis(X, weights, is_benefit, verbose=False):
    """
    X          : ma trận quyết định (n_alt × n_crit)
    weights    : trọng số (tổng = 1)
    is_benefit : list bool
    """
    weights = np.array(weights)

    # Bước 1: Chuẩn hóa vector
    # r_ij = x_ij / sqrt(Σ x_ij²)
    norm_factor = np.sqrt((X**2).sum(axis=0))
    R = X / norm_factor

    if verbose:
        print("  Bước 1 — Ma trận chuẩn hóa R:")
        df_r = pd.DataFrame(R.round(4), index=regions,
                            columns=ten_tieu_chi)
        print(df_r.to_string())

    # Bước 2: Ma trận chuẩn hóa có trọng số
    # v_ij = w_j × r_ij
    V = R * weights

    if verbose:
        print("\n  Bước 2 — Ma trận có trọng số V:")
        df_v = pd.DataFrame(V.round(4), index=regions,
                            columns=ten_tieu_chi)
        print(df_v.to_string())

    # Bước 3: Lời giải lý tưởng dương A* và âm A-
    A_star = np.where(is_benefit, V.max(axis=0), V.min(axis=0))
    A_neg  = np.where(is_benefit, V.min(axis=0), V.max(axis=0))

    if verbose:
        print(f"\n  Bước 3 — A* (lý tưởng dương): "
              f"{A_star.round(4)}")
        print(f"           A- (lý tưởng âm)  : "
              f"{A_neg.round(4)}")

    # Bước 4: Khoảng cách Euclide
    S_star = np.sqrt(((V - A_star)**2).sum(axis=1))
    S_neg  = np.sqrt(((V - A_neg )**2).sum(axis=1))

    if verbose:
        print(f"\n  Bước 4 — S* : {S_star.round(4)}")
        print(f"           S- : {S_neg.round(4)}")

    # Bước 5: Hệ số gần gũi tương đối C*
    C_star = S_neg / (S_star + S_neg)

    return {
        'C_star' : C_star,
        'S_star' : S_star,
        'S_neg'  : S_neg,
        'V'      : V,
        'A_star' : A_star,
        'A_neg'  : A_neg,
        'rank'   : np.argsort(C_star)[::-1]
    }


